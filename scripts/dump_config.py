"""Write the configuration that the scripts actually use to
configs/resolved_config.yaml.

The settings live as constants in the code (single source of truth); this
script imports them and writes them out, so the YAML file cannot drift from
the code. It is regenerated by scripts/make_all_tables.sh.

Usage:  python scripts/dump_config.py
"""
import inspect
import subprocess
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import b2_shift_zero_shot as b2  # noqa: E402
import b3_gap_plot as b3  # noqa: E402
import c1_retrieval as c1  # noqa: E402
import c4_failure_cases as c4  # noqa: E402
import c6_latency as c6  # noqa: E402
from src import embed, gap, metrics, models  # noqa: E402


def lst(x):
    return [float(v) for v in np.asarray(x)]


def main():
    cfg = {
        "_note": "Generated by scripts/dump_config.py from the constants in the code. Do not edit by hand.",
        "git_commit": subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                                     capture_output=True, text=True).stdout.strip(),
        "models": {k: {"open_clip_arch": a, "pretrained": t} for k, (a, t) in models.MODELS.items()},
        "embedding": {
            "batch_size": inspect.signature(embed.Encoder.__init__).parameters["batch_size"].default, "precision": "fp32", "l2_normalized": True,
            "classification_prompts": embed.PROMPTS, "eurosat_class_names": embed.EUROSAT_CLASSES,
            "classification_train_subset": embed.TRAIN_SUBSET,
            "classification_train_subset_seed": embed.TRAIN_SUBSET_SEED,
            "retrieval_sets": {k: list(v) for k, v in embed.RETRIEVAL_SETS.items()},
        },
        "bootstrap": {"n_resamples": metrics.N_BOOT, "ci": 0.95, "unit": "test queries (paired for differences)"},
        "shift_mind_the_gap": {"formula": "img' = norm(img - 0.5*delta*u), txt' = norm(txt + 0.5*delta*u), u = Delta/||Delta||",
                               "delta_grid": lst(gap.SHIFT_GRID)},
        "partial_centering_M4": {"formula": "x' = norm(x - alpha*mu_x)", "alpha_grid": lst(gap.ALPHA_GRID),
                                 "selection": "validation Recall@1, separately for I2T and T2I; ties -> smallest |value|"},
        "zero_shot_B2b": {"datasets": b2.DATASETS, "split_seed": b2.SPLIT_SEED, "n_calibration": b2.N_CAL,
                          "n_validation": b2.N_VAL, "eurosat_test_fraction": 0.2},
        "retrieval_C1": {"split_seed": c1.SPLIT_SEED, "n_validation_images": c1.N_VAL,
                         "calibration_sizes": c1.CAL_SIZES, "calibration_seeds": c1.CAL_SEEDS,
                         "calibration_draw_rng": "default_rng(1000 + seed)", "main_calibration_size": c1.MAIN_N,
                         "random_shift_seeds_C1": c1.C1_SEEDS, "recall_ks": list(c1.KS),
                         "out_of_domain_source": c1.OTHER, "protocols": ["5cap", "first (Flickr30k only)"]},
        "gap_plot_B3": {"n_pairs": b3.N_PAIRS, "seed": b3.SEED, "pairs_with_lines": b3.N_LINES},
        "failure_cases": {"n_per_kind": c4.N_SHOW, "calibration_seed": c4.SEED},
        "latency": {"n_queries": c6.N_Q, "n_warmup": c6.N_WARM},
    }
    out = ROOT / "configs" / "resolved_config.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text(yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
